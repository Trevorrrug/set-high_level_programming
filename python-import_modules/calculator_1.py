#!/usr/bin/python3
"""Defines basic mathematical operations."""


def add(a, b):
    """Return the sum of two numbers."""
    return a + b


def sub(a, b):
    """Return the difference between two numbers."""
    return a - b


def mul(a, b):
    """Return the product of two numbers."""
    return a * b


def div(a, b):
    """Return the division of two numbers."""
    return int(a / b)
